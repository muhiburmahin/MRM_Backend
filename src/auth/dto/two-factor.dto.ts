import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsOptional, IsString, Length, Matches } from 'class-validator';

export class VerifyTwoFactorLoginDto {
  @ApiProperty({ description: 'Temporary 2FA ticket returned by /auth/login' })
  @IsString()
  @IsNotEmpty()
  twoFactorTicket!: string;

  @ApiProperty({ description: '6-digit TOTP code or backup recovery code' })
  @IsString()
  @IsNotEmpty()
  code!: string;
}

export class EnableTwoFactorDto {
  @ApiProperty({
    description: '6-digit TOTP code generated by authenticator app',
    example: '123456',
  })
  @IsString()
  @Length(6, 6)
  @Matches(/^\d{6}$/, { message: 'Verification code must be exactly 6 digits' })
  code!: string;
}

export class DisableTwoFactorDto {
  @ApiProperty({ description: 'Current password for verification' })
  @IsString()
  @IsNotEmpty()
  password!: string;

  @ApiProperty({ description: 'Optional 6-digit TOTP code', required: false })
  @IsString()
  @IsOptional()
  code?: string;
}

export class RegenerateRecoveryCodesDto {
  @ApiProperty({ description: 'Current password for verification' })
  @IsString()
  @IsNotEmpty()
  password!: string;
}

export class TwoFactorSetupResponse {
  @ApiProperty({ description: 'Base32 secret key for manual entry' })
  secret!: string;

  @ApiProperty({ description: 'otpauth:// URI for authenticator QR code generation' })
  uri!: string;
}

export class TwoFactorEnableResponse {
  @ApiProperty({ description: 'One-time backup recovery codes', type: [String] })
  recoveryCodes!: string[];
}

export class TwoFactorStatusResponse {
  @ApiProperty({ description: 'Whether 2FA is currently active for the user' })
  enabled!: boolean;
}
